/// Kinds of objects shown in the database explorer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum ObjectKind {
    Table,
    View,
    MaterializedView,
    ForeignTable,
    Sequence,
    Function,
    Procedure,
    Trigger,
    Type,
}

impl ObjectKind {
    /// Group label in the explorer.
    pub fn group_label(self) -> &'static str {
        match self {
            ObjectKind::Table => "tables",
            ObjectKind::View => "views",
            ObjectKind::MaterializedView => "materialized views",
            ObjectKind::ForeignTable => "foreign tables",
            ObjectKind::Sequence => "sequences",
            ObjectKind::Function => "routines",
            ObjectKind::Procedure => "procedures",
            ObjectKind::Trigger => "triggers",
            ObjectKind::Type => "types",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            ObjectKind::Table => "table",
            ObjectKind::View => "view",
            ObjectKind::MaterializedView => "materialized view",
            ObjectKind::ForeignTable => "foreign table",
            ObjectKind::Sequence => "sequence",
            ObjectKind::Function => "function",
            ObjectKind::Procedure => "procedure",
            ObjectKind::Trigger => "trigger",
            ObjectKind::Type => "type",
        }
    }

    /// Objects whose rows can be browsed.
    pub fn has_data(self) -> bool {
        matches!(self, ObjectKind::Table | ObjectKind::View | ObjectKind::MaterializedView | ObjectKind::ForeignTable)
    }

    /// Objects that have columns, indexes and keys.
    pub fn has_columns(self) -> bool {
        self.has_data()
    }
}

/// Where an object lives. For engines without schemas (MySQL, SQLite) the
/// schema equals the database.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct ObjectPath {
    pub database: String,
    pub schema: String,
    pub name: String,
}

impl ObjectPath {
    pub fn new(database: impl Into<String>, schema: impl Into<String>, name: impl Into<String>) -> Self {
        Self { database: database.into(), schema: schema.into(), name: name.into() }
    }
}

/// An object listed in a schema.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DbObject {
    pub kind: ObjectKind,
    pub path: ObjectPath,
    /// Extra text shown next to the name: a routine's arguments, a trigger's table.
    pub detail: Option<String>,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ColumnInfo {
    pub name: String,
    /// Full type as written in DDL, e.g. `character varying(20)`.
    pub data_type: String,
    pub nullable: bool,
    pub default: Option<String>,
    pub primary_key: bool,
    /// Generated by the server (serial, identity, AUTO_INCREMENT, rowid alias).
    pub auto_increment: bool,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct IndexInfo {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
    pub primary: bool,
    /// Access method (`btree`, `hash`, `gin`…), if known.
    pub method: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ForeignKeyInfo {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    pub on_update: String,
    pub on_delete: String,
}

/// Structure of a table or view.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TableDetails {
    pub columns: Vec<ColumnInfo>,
    pub indexes: Vec<IndexInfo>,
    pub foreign_keys: Vec<ForeignKeyInfo>,
    pub comment: Option<String>,
}

impl TableDetails {
    pub fn primary_key(&self) -> Vec<&str> {
        self.columns.iter().filter(|c| c.primary_key).map(|c| c.name.as_str()).collect()
    }
}
