//! Fills a parent and a child table with generated rows on every engine and
//! checks the counts, unique values and foreign keys. SQLite and DuckDB always
//! run; the servers need the `DBMAN_TEST_*` variables (see `transfer.rs`).

use std::collections::HashSet;
use std::sync::Arc;
use std::sync::atomic::AtomicBool;

use dbman_core::generate::{Kind, default_plan};
use dbman_core::sql::Dialect;
use dbman_core::{Cell, Connection, ConnectionConfig, DbKind, ObjectPath, StatementOutcome};
use dbman_drivers::generate::{GenerateJob, generate};

fn from_url(kind: DbKind, var: &str) -> Option<ConnectionConfig> {
    let url = std::env::var(var).ok().filter(|u| !u.is_empty())?;
    let rest = url.split_once("://").map(|(_, r)| r).unwrap_or(&url);
    let (auth, addr) = rest.rsplit_once('@').unwrap_or(("", rest));
    let (user, password) = auth.split_once(':').unwrap_or((auth, ""));
    let (hostport, db) = addr.split_once('/').unwrap_or((addr, ""));
    let (host, port) = hostport.split_once(':').unwrap_or((hostport, ""));
    let mut cfg = ConnectionConfig::new(kind);
    cfg.host = host.into();
    if let Ok(p) = port.parse() {
        cfg.port = p;
    }
    cfg.user = user.into();
    cfg.password = password.into();
    cfg.database = db.into();
    cfg.ssl_mode = if kind == DbKind::MsSql { dbman_core::SslMode::Prefer } else { dbman_core::SslMode::Disable };
    Some(cfg)
}

async fn exec(c: &Arc<dyn Connection>, db: &str, sql: &str) -> StatementOutcome {
    c.execute(Some(db), sql, usize::MAX / 2).await.unwrap_or_else(|e| panic!("{sql}: {e}"))
}

/// Parent and child tables in an engine's dialect (`{p}`, `{c}` are their names).
fn tables_sql(kind: DbKind) -> [&'static str; 2] {
    match kind {
        DbKind::Redis => unreachable!("Redis has no tables"),
        DbKind::Postgres => [
            "CREATE TABLE {p} (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(40) NOT NULL, \
             country varchar(30))",
            "CREATE TABLE {c} (id integer PRIMARY KEY, parent_id integer NOT NULL REFERENCES {p}(id), \
             email varchar(60) NOT NULL UNIQUE, amount numeric(10,2), flag boolean, created timestamp, \
             note text, data bytea)",
        ],
        DbKind::MySql => [
            "CREATE TABLE {p} (id int AUTO_INCREMENT PRIMARY KEY, name varchar(40) NOT NULL, country varchar(30))",
            "CREATE TABLE {c} (id int PRIMARY KEY, parent_id int NOT NULL, email varchar(60) NOT NULL UNIQUE, \
             amount decimal(10,2), flag tinyint(1), created datetime, note text, data blob, \
             status enum('new','paid','sent'), FOREIGN KEY (parent_id) REFERENCES {p}(id))",
        ],
        DbKind::Sqlite => [
            "CREATE TABLE {p} (id INTEGER PRIMARY KEY, name VARCHAR(40) NOT NULL, country VARCHAR(30))",
            "CREATE TABLE {c} (id INTEGER PRIMARY KEY, parent_id INTEGER NOT NULL REFERENCES parent_t(id), \
             email VARCHAR(60) NOT NULL UNIQUE, amount NUMERIC(10,2), flag BOOLEAN, created TIMESTAMP, note TEXT, \
             data BLOB)",
        ],
        DbKind::DuckDb => [
            "CREATE TABLE {p} (id INTEGER PRIMARY KEY, name VARCHAR(40) NOT NULL, country VARCHAR(30))",
            "CREATE TABLE {c} (id INTEGER PRIMARY KEY, parent_id INTEGER NOT NULL REFERENCES {p}(id), \
             email VARCHAR(60) NOT NULL UNIQUE, amount DECIMAL(10,2), flag BOOLEAN, created TIMESTAMP, note VARCHAR, \
             data BLOB)",
        ],
        DbKind::MsSql => [
            "CREATE TABLE {p} (id int IDENTITY PRIMARY KEY, name nvarchar(40) NOT NULL, country nvarchar(30))",
            "CREATE TABLE {c} (id int PRIMARY KEY, parent_id int NOT NULL REFERENCES {p}(id), \
             email nvarchar(60) NOT NULL UNIQUE, amount decimal(10,2), flag bit, created datetime2, \
             note nvarchar(max), data varbinary(max))",
        ],
        DbKind::ClickHouse => [
            "CREATE TABLE {p} (id Int32, name String, country Nullable(String)) ENGINE = MergeTree ORDER BY id",
            "CREATE TABLE {c} (id Int32, parent_id Int32, email String, amount Nullable(Decimal(10,2)), \
             flag Nullable(Bool), created Nullable(DateTime), note Nullable(String), \
             status Enum8('new' = 1, 'paid' = 2)) ENGINE = MergeTree ORDER BY id",
        ],
    }
}

/// An engine with the database and schema the tables go in.
struct Place {
    kind: DbKind,
    cfg: ConnectionConfig,
    db: String,
    schema: String,
}

async fn places(dir: &std::path::Path) -> Vec<Place> {
    let mut out = Vec::new();
    let mut sqlite = ConnectionConfig::new(DbKind::Sqlite);
    sqlite.database = dir.join("gen.db").to_string_lossy().into_owned();
    out.push(Place { kind: DbKind::Sqlite, cfg: sqlite, db: "main".into(), schema: "main".into() });
    let mut duck = ConnectionConfig::new(DbKind::DuckDb);
    duck.database = dir.join("gen.duckdb").to_string_lossy().into_owned();
    out.push(Place { kind: DbKind::DuckDb, cfg: duck, db: "gen".into(), schema: "main".into() });
    if let Some(cfg) = from_url(DbKind::Postgres, "DBMAN_TEST_POSTGRES") {
        let db = cfg.database.clone();
        let c = dbman_drivers::connect(&cfg).await.unwrap();
        exec(&c, &db, "DROP SCHEMA IF EXISTS gen_test CASCADE").await;
        exec(&c, &db, "CREATE SCHEMA gen_test").await;
        out.push(Place { kind: DbKind::Postgres, cfg, db, schema: "gen_test".into() });
    }
    if let Some(cfg) = from_url(DbKind::MySql, "DBMAN_TEST_MYSQL") {
        let base = cfg.database.clone();
        let c = dbman_drivers::connect(&cfg).await.unwrap();
        let db = format!("{base}_gen");
        exec(&c, &base, &format!("DROP DATABASE IF EXISTS `{db}`")).await;
        exec(&c, &base, &format!("CREATE DATABASE `{db}`")).await;
        let mut cfg = cfg;
        cfg.database = db.clone();
        out.push(Place { kind: DbKind::MySql, cfg, db: db.clone(), schema: db });
    }
    if let Some(cfg) = from_url(DbKind::MsSql, "DBMAN_TEST_MSSQL") {
        let db = cfg.database.clone();
        let mut master = cfg.clone();
        master.database = "master".into();
        let m = dbman_drivers::connect(&master).await.unwrap();
        exec(&m, "master", &format!("IF DB_ID(N'{db}') IS NULL CREATE DATABASE [{db}]")).await;
        let c = dbman_drivers::connect(&cfg).await.unwrap();
        exec(&c, &db, "DROP TABLE IF EXISTS gen_test.child_t").await;
        exec(&c, &db, "DROP TABLE IF EXISTS gen_test.parent_t").await;
        exec(&c, &db, "IF SCHEMA_ID(N'gen_test') IS NULL EXEC(N'CREATE SCHEMA gen_test')").await;
        out.push(Place { kind: DbKind::MsSql, cfg, db, schema: "gen_test".into() });
    }
    if let Some(cfg) = from_url(DbKind::ClickHouse, "DBMAN_TEST_CLICKHOUSE") {
        let base = cfg.database.clone();
        let c = dbman_drivers::connect(&cfg).await.unwrap();
        exec(&c, &base, "DROP DATABASE IF EXISTS gen_test").await;
        exec(&c, &base, "CREATE DATABASE gen_test").await;
        out.push(Place { kind: DbKind::ClickHouse, cfg, db: "gen_test".into(), schema: "gen_test".into() });
    }
    out
}

fn texts(o: &StatementOutcome) -> Vec<String> {
    let StatementOutcome::Rows(r) = o else { panic!("{o:?}") };
    r.rows
        .iter()
        .map(|row| match &row[0] {
            Cell::Text(s) => s.clone(),
            other => format!("{other:?}"),
        })
        .collect()
}

#[tokio::test(flavor = "multi_thread")]
async fn fills_parent_and_child_tables() {
    let dir = tempfile::tempdir().unwrap();
    for p in places(dir.path()).await {
        let c = dbman_drivers::connect(&p.cfg).await.unwrap();
        let d = Dialect(p.kind);
        let parent = ObjectPath::new(&p.db, &p.schema, "parent_t");
        let child = ObjectPath::new(&p.db, &p.schema, "child_t");
        let [ps, cs] = tables_sql(p.kind);
        let (pq, cq) = (d.qualified(&parent), d.qualified(&child));
        exec(&c, &p.db, &ps.replace("{p}", &pq)).await;
        exec(&c, &p.db, &cs.replace("{p}", &pq).replace("{c}", &cq)).await;

        let run = |path: ObjectPath, rows: u64, clear_first: bool| {
            let c = c.clone();
            let cfg = p.cfg.clone();
            let kind = p.kind;
            async move {
                let details = c.table_details(&path).await.unwrap();
                let mut plan = default_plan(kind, &details);
                // ClickHouse has no foreign keys or identity: point and count by hand.
                if kind == DbKind::ClickHouse {
                    for col in &mut plan {
                        match col.column.as_str() {
                            "id" => col.kind = Kind::Sequence { start: 1 },
                            "parent_id" => col.kind = Kind::Reference { table: "parent_t".into(), column: "id".into() },
                            "email" => col.unique = true,
                            _ => {}
                        }
                    }
                }
                let job = GenerateJob { table: path, rows, plan, seed: 7, clear_first, batch_rows: 200 };
                let report: dbman_drivers::backup::Report = Arc::new(|_| {});
                generate(cfg, job, report, Arc::new(AtomicBool::new(false))).await
            }
        };
        run(parent.clone(), 50, false).await.unwrap_or_else(|e| panic!("{:?} parent: {e}", p.kind));
        run(child.clone(), 500, false).await.unwrap_or_else(|e| panic!("{:?} child: {e}", p.kind));
        // Again: the key goes on after the rows already there.
        run(child.clone(), 100, false).await.unwrap_or_else(|e| panic!("{:?} child again: {e}", p.kind));

        let count = |t: &str| format!("SELECT COUNT(*) FROM {t}");
        assert_eq!(texts(&exec(&c, &p.db, &count(&pq)).await), ["50"], "{:?}", p.kind);
        assert_eq!(texts(&exec(&c, &p.db, &count(&cq)).await), ["600"], "{:?}", p.kind);
        let emails: HashSet<String> =
            texts(&exec(&c, &p.db, &format!("SELECT email FROM {cq}")).await).into_iter().collect();
        assert_eq!(emails.len(), 600, "{:?}: emails repeat", p.kind);
        let orphans = format!("SELECT COUNT(*) FROM {cq} WHERE parent_id NOT IN (SELECT id FROM {pq})");
        assert_eq!(texts(&exec(&c, &p.db, &orphans).await), ["0"], "{:?}", p.kind);

        // Replacing: the rows go, new ones come.
        run(child.clone(), 30, true).await.unwrap_or_else(|e| panic!("{:?} replace: {e}", p.kind));
        assert_eq!(texts(&exec(&c, &p.db, &count(&cq)).await), ["30"], "{:?}", p.kind);
    }
}
